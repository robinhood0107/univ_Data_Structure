/*
“DP 문제인지 먼저 판정하고 해결하는 기법” 정리

어떤 새로운 문제가 나왔을 때
“이거 DP로 풀 수 있는 문제인가?”를 판정하는 일반적인 단계는 보통 다음과 같다.

① 상태(부분 문제) 정의하기

예: dp[n] = n원을 만들기 위한 최소 동전 수

부분 문제를 “조금 작은 버전의 같은 문제”로 잡을 수 있는지 본다.

② 점화식(an = 5x an-1 + 3) 세우기: 실제 한자는 遞換式(체환식)

n원을 만드는 방법을 더 작은 금액들의 조합으로 표현할 수 있는지 본다.

현재 문제를 “이전 상태들”로 표현할 수 있으면 후보.

예:
dp[n] = 1 + min(dp[n-1], dp[n-5], dp[n-10], dp[n-25])

③ Optimal Substructure 검증

“전체 최적해가 부분 문제들의 최적해로부터 구성되나?”를 논리적으로 확인.

보통 ‘마지막 선택을 하나 떼어내고’, 남은 부분이 최적인지 논리적으로 증명(모순법 형태).

④ Overlapping Subproblems 확인

재귀식에 따라 계속 쪼개 보면 똑같은 상태가 여러 번 등장하는지 확인.

예: f(63)을 풀다가 f(53), f(38) 등 같은 값을 여러 번 계산하게 되는지 살펴본다.

“상태의 개수는 작고(63개), 그 상태들이 여러 번 재사용된다” → DP 적합

⑤ 문제 풀이 방식

메모이제이션 (Top-Down)으로 중첩 계산
-> recurrence relation으로 문제 정의
*/
