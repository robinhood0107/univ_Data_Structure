/*
1원/5원/10원/25원 동전으로 63원을 만들 때 필요한 최소 동전 개수

금액 n원을 만들 때 필요한 최소 동전 개수를 다음과 같이 정의.

dp[n] = n원을 만들기 위한 최소 동전 개수

동전이 1, 5, 10, 25원이므로,
마지막에 쓰는 동전 하나를 c라고 하면 (c ∈ {1, 5, 10, 25})

dp[n]=1+min{dp[n−1],dp[n−5],dp[n−10],dp[n−25]}

단, n - coin ≥ 0인 경우만 고려.

기본값(초기 조건)은

dp[0] = 0 (0원을 만드는 데 필요한 동전의 수는 0개)

이 점화식을 이용해 1원부터 63원까지 순서대로 채워 나간다.

이 문제가 왜 DP 문제인가?
(1) Optimal Substructure 판정

**Optimal Substructure (최적 부분 구조)**란:

“전체 문제의 최적해가, 그 안에 포함된 부분 문제들의 최적해들로부터 구성될 수 있는가?”



이 문제(63원 최소 동전)에서 이걸 직접 확인해보면:

63원을 만드는 어떤 최적 해를 생각해 봅시다.

그 해에서 마지막에 사용한 동전을 하나 떼어내면, 남는 금액은

63 - 1 = 62

63 - 5 = 58

63 - 10 = 53

63 - 25 = 38
중 하나입니다.

예를 들어, 최적 해가

63원 = 25 + 25 + 10 + 1 + 1 + 1

Overlapping Subproblems 판정


**Overlapping Subproblems (중첩 부분 문제)**란:

“재귀적으로 문제를 쪼개다 보면
서로 다른 경로에서 같은 부분 문제가 반복해서 등장하는가?”

를 뜻합니다.

동전 거스름돈 문제를 재귀적으로 풀면 예를 들어:

f(63)을 계산할 때

f(63)은 f(62), f(58), f(53), f(38)을 호출

f(62)는 또 f(61), f(57), f(52), f(37)을 호출

f(58)는 f(57), f(53), f(48), f(33)을 호출

…

이렇게 내려가다 보면
f(53), f(38), f(33) 등 같은 금액에 대한 함수가 여러 번 호출.

즉, 재귀 호출 트리에서는 같은 금액에 대한 문제를 여러 경로에서 반복해서 계산이 overlapping.
*/
