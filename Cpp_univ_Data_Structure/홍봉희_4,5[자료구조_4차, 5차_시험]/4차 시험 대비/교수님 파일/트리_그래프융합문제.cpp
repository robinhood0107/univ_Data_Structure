/*
최소 공통 조상 (LCA, Lowest Common Ancestor) 문제
- LCA: 두 node u와 v의 LCA는 u와 v를 모두 자손으로 가지는 조상 노드들 중에서 
  루트(Root)로부터 가장 멀리 떨어진 (즉, 깊이가 가장 깊은) 노드

- 해법:
단계별 풀이 (조상 추적)

1) 조상 경로 표시 (u → Root):
  - 노드 u에서 시작하여 부모 배열을 따라 루트까지 거슬러 올라가면서, 지나온 모든 정점을 방문(visited) 또는 표시
  합니다.
  
2) LCA 찾기 (v → Root):

  - 노드 v에서 시작하여 부모 배열을 따라 루트까지 거슬러 올라간다.
    이 경로에서 처음으로 표시된(visited) 노드를 만나는 순간, 그 정점이 바로 u와 v의 LCA가 된다.

구현 방법1: 각 노드에 parent 필드 추가 > 이 방법은 동적 메모리 할당(힙)과 포인터 관리의 복잡성을 증가시키기 때문에 비추
//좋지 않은 방법

구현 방법2: 그래프 표현-인접 리스트와 parent 배열 사용

  - 트리를 인접 리스트로 표현
  - 주어진 트리에 대하여 인접 리스트로 표현된 트리에 대하여 DFS를 시행, parent 배열과 깊이를 배열에 저장
    parent[u] > u의 부모 노드 번호            //배열
    depth[u] > u의 깊이 (루트로부터의 거리)    //배열
*/
void DFS(int u, int p, int d) {
    parent[u] = p; // 부모 정보 저장
    depth[u] = d;  // 깊이 정보 저장

    for (int v : adj[u]) {
        if (v != p) { // 부모(p)로 다시 돌아가는 것 방지
            DFS(v, u, d + 1); // 재귀 호출: u가 v의 부모
        }
    }
}

